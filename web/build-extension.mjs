// Copies the shared start page renderer into the extension, so that the extension ships it inside
// its own package (Mozilla's add-on review forbids remote code). The sources stay where they are:
//
//   static/magpie/render.js   -> extension/vendor/render.js
//   static/magpie/render.css  -> extension/vendor/render.css
//   web/kit-tokens.css        -> extension/vendor/tokens.css (the kit tokens render.css needs)
//
// and writes one file that no source holds as it is:
//
//   locales/en.toml, locales/nb.toml ([detail]) -> extension/vendor/detail-labels.js
//
// the titles and labels of detail blocks (lists, bars and the like), which the service kinds name by
// key under [detail]; the extension has no server to ask, so it ships them. A new key in the locale
// files needs this script run again.
//
// The files in extension/vendor/ are committed. CI runs this script and fails when the result
// differs from what is committed (git diff --exit-code), so a changed renderer cannot reach the
// extension by accident. Run it with `npm run build:extension` in web/.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// [source, target] pairs, relative to the repository root.
export const files = [
  ["static/magpie/render.js", "extension/vendor/render.js"],
  ["static/magpie/render.css", "extension/vendor/render.css"],
  ["web/kit-tokens.css", "extension/vendor/tokens.css"],
];

/** The target of the generated file of the detail texts. */
export const detailTarget = "extension/vendor/detail-labels.js";

/** The `[detail]` section of a locale file as `{ key: text }`, in file order. */
export function detailTexts(toml) {
  const texts = {};
  let inside = false;
  for (const line of toml.split(/\r?\n/)) {
    const header = line.match(/^\[([^\]]+)\]\s*$/);
    if (header) {
      inside = header[1] === "detail";
      continue;
    }
    const entry = inside ? line.match(/^([A-Za-z0-9_.]+)\s*=\s*"((?:[^"\\]|\\.)*)"\s*$/) : null;
    // The locale files' escapes (\", \\ and \n) are JSON's.
    if (entry) texts[entry[1]] = JSON.parse(`"${entry[2]}"`);
  }
  return texts;
}

/** The text of the generated file. */
export function detailSource() {
  const read = (lang) => detailTexts(readFileSync(join(root, "locales", `${lang}.toml`), "utf8"));
  return `// Generated by web/build-extension.mjs from the [detail] sections of locales/en.toml and
// locales/nb.toml. Do not edit: run \`npm run build:extension\` in web/.
export const detail = ${JSON.stringify({ en: read("en"), nb: read("nb") }, null, 2)};
`;
}

/** Copies the files under `outRoot` (the repository root by default), and writes the generated one. Returns the target paths. */
export function build(outRoot = root) {
  const written = [];
  for (const [source, target] of files) {
    const to = join(outRoot, target);
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(join(root, source), to);
    written.push(target);
  }
  writeFileSync(join(outRoot, detailTarget), detailSource());
  written.push(detailTarget);
  return written;
}

/** The targets whose content differs from its source under `outRoot`, or that are missing. */
export function stale(outRoot = root) {
  const out = [];
  for (const [source, target] of files) {
    let current = null;
    try {
      current = readFileSync(join(outRoot, target));
    } catch {
      current = null;
    }
    if (current === null || !current.equals(readFileSync(join(root, source)))) out.push(target);
  }
  let generated = null;
  try {
    generated = readFileSync(join(outRoot, detailTarget), "utf8");
  } catch {
    generated = null;
  }
  if (generated !== detailSource()) out.push(detailTarget);
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const target of build()) console.log(`wrote ${target}`);
}
